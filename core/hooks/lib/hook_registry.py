"""
Hook Registry — event-keyed, ordered registry of PreToolUse / PostToolUse hook
registrations, seeded from ~/.claude/settings.json array order.

VERSION: 1.5.0  (rp1-home#2613: the loader fallbacks report loudly, once per process —
                 _report_loader_unavailable, shared by every fallback site.
                 1.4.0 — rp1-home#2212: get_entries merges plugin fragments after the
                 core literal; get_hook_path returns a resolved absolute fragment path
                 unchanged — both additive, byte no-op with zero fragment plugins)

Part of the hook-layer consolidation (epic #1729, sub-issue A — #1730). This
module is the single source of truth for WHICH standalone hook scripts run for a
given tool event, in WHICH order, under WHICH matcher. It is consumed by
`hook-dispatcher.py` (the Level-1 in-process adapter) and by downstream
sub-issues #1734 / #1735, which import `EVENT_REGISTRY` / `get_entries` and MUST
NOT re-parse settings.json themselves — the registry centralizes that once.

Design (mirrors lib/detector_registry.py's shape, extended to be event-keyed):

- `EVENT_REGISTRY` is a STATIC, committed literal — the durable API surface, so
  downstream consumers import a plain data structure with no runtime settings.json
  dependency. Its content was generated by parsing settings.json array order (the
  "obtain the seed programmatically" discipline — see `_parse_settings_entries`,
  which reproduces the exact generator), so it matches settings.json byte-for-byte
  at the pin. Because it is static it CAN drift if settings.json changes;
  `validate_against_settings()` is the callable drift check, reporting `mode:
  "corpus"` (the pre-#1732 state where settings.json SEEDED the corpus and was
  authoritative) vs `mode: "dispatcher"` (the live post-cutover reality — the
  corpus parse is empty and this registry is the sole corpus surface, so there is
  nothing to diff). Always add a NEW hook by adding an `Entry(...)` to
  `EVENT_REGISTRY` here, never by editing settings.json, because post-#1735 this
  registry is the AUTHORITATIVE single registration surface and settings.json
  carries ONLY the two per-event `hook-dispatcher.py` meta-registrations — not the
  individual-hook corpus. The forward / reverse / single-surface enforcement lives
  in `validate_registrations()` in `.claude/hooks/lib/hook_registration_validator.py`,
  and this registry never silently drops a registration.

- Seed order == settings.json array order: matcher-group order, then command order
  within a group. A file registered under multiple matchers (e.g.
  `version-bump-enforcer` under `[Edit]` and `[Write]`) yields ONE `Entry` per
  registration, preserving multi-registration fidelity — settings.json array order
  already encodes it, so no `# HOOK_EVENT_2`-header expansion is needed (those
  numbered headers are the file's self-documentation of the same fact).

- Header cross-check caveat (#1730 Task 1, SEED-TIME history): when this registry
  was first SEEDED from settings.json array order at the pin, a file's `# HOOK_*`
  self-doc headers could disagree with settings.json's actual registrations (e.g.
  `claude-md-direct-edit-blocker.py` had THREE settings.json registrations —
  MultiEdit / Edit / Write — but only Edit + a `_2` Write header); the seed kept
  every settings.json registration, because settings.json array order was the
  authoritative SEED at that time. Post-#1735 this is history — `EVENT_REGISTRY`
  below is the authoritative corpus and settings.json carries only the dispatcher
  meta-registrations (see the `EVENT_REGISTRY` bullet above).

The registry stores the matcher STRING uninterpreted; the dispatcher's matcher
engine (hook-dispatcher.py) is the sole place that decides exact-list vs regex.

See: rp1-home#1730
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field

__version__ = "1.5.0"

# This module lives in .claude/hooks/lib/, so the hooks directory is its parent's
# parent. Resolved from the module's own location so it is correct both in a
# worktree checkout (tests) and live from ~/.claude/hooks/ (post-#1732 cutover).
HOOKS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The settings.json that seeds this registry, resolved relative to HOOKS_DIR so a
# worktree self-check reads its own committed settings.json. The drift validator
# accepts an explicit path override for testing against a specific file.
DEFAULT_SETTINGS_PATH = os.path.join(os.path.dirname(HOOKS_DIR), "settings.json")


@dataclass(frozen=True)
class Entry:
    """One (event, matcher, module) registration.

    matcher: the matcher STRING verbatim as it appears in settings.json — ``""``
        or ``"*"`` (match-all), an exact tool name (``"Bash"``), an exact-name
        alternation list (``"Edit|Write"``), or a regex prefix
        (``"mcp__claude-in-chrome__"``). The dispatcher's matcher engine interprets
        it; the registry stores it uninterpreted.
    module: the hook basename WITHOUT extension (e.g. ``"version-bump-enforcer"``,
        ``"check-approval-sentinel"``). Resolve to an on-disk path with
        :func:`get_hook_path`.
    kind: ``"inprocess"`` (a python hook run in-process via stdin-inject +
        stdout-capture + SystemExit-catch) or ``"subprocess"`` (a non-python or
        stubborn hook run via ``subprocess.run`` — the sanctioned Level-1 escape
        hatch).
    flags: reserved for per-entry execution flags (empty for the seed set).
    """

    matcher: str
    module: str
    kind: str = "inprocess"
    # `flags` is carry-only metadata; excluded from __eq__/__hash__ so a frozen
    # Entry stays hashable (a dict field is unhashable) and two entries are equal
    # iff their (matcher, module, kind) match — the identity the tuple-diff uses.
    flags: dict = field(default_factory=dict, compare=False)


# The single non-python registered hook (check-approval-sentinel.sh, 348 lines of
# shell) is run via the subprocess-fallback entry type — NOT ported under Level-1
# discipline (#1730 Task 5). Add any python hook that resists in-process execution
# here if #1731's adapter tests surface one.
SUBPROCESS_MODULES = frozenset({"check-approval-sentinel"})


# ─────────────────────────────────────────────────────────────────────────────
# EVENT_REGISTRY — static committed literal, generated from settings.json array
# order. PreToolUse + PostToolUse were the #1730/#1732 seed; #1734 adds the
# Phase-2 events Stop / SessionStart / UserPromptSubmit / PostToolUseFailure
# (see the Phase-2 block at the end of the literal, pinned in pre-flip array order).
# REGENERATE the Pre/Post section with the generator reproduced by
# `_parse_settings_entries` (or the equivalent jq extraction) whenever settings.json
# changes; `validate_against_settings()` is the drift guard for Pre/Post (the
# Phase-2 events' single-surface drift validation is #1735's scope).
# ─────────────────────────────────────────────────────────────────────────────
EVENT_REGISTRY: dict[str, list[Entry]] = {
    "PreToolUse": [
        Entry('', 'tool-timeout-enforcer'),
    ],
    "PostToolUse": [
        Entry('Edit|Write', 'lint-on-write'),
        Entry('', 'idle-pattern-detector'),
    ],
    "Stop": [],
    "SessionStart": [
        Entry('', 'plugin-fragment-version-warner'),
    ],
    "UserPromptSubmit": [
        Entry('', 'unified-prompt-dispatcher'),
    ],
    "PostToolUseFailure": [
        Entry('', 'stall-logger'),
    ],
}


# ─────────────────────────────────────────────────────────────────────────────
# Accessors (mirror detector_registry.get_detector_path, extended)
# ─────────────────────────────────────────────────────────────────────────────
def get_entries(event: str) -> list[Entry]:
    """Return the ordered list of :class:`Entry` for an event, core-first, with any
    enabled plugin fragments' entries merged AFTER the core literal (rp1-home#2212).

    ``event`` is any registered event (``"PreToolUse"``, ``"SessionStart"``, …).
    Unknown events return an empty list. The static ``EVENT_REGISTRY`` literal is
    NEVER written back — it stays the core source of truth; the merge is additive.

    Merge policy (``lib.plugin_fragments.merged_event_entries``): a byte no-op when
    no fragment-bearing plugin is enabled (R2 order-diff invariant); otherwise each
    enabled plugin's ``EVENT_ENTRIES[event]`` is appended in ``PLUGIN_ORDER``-then-name
    order, with a fragment entry whose module basename duplicates a core module for
    this event SHADOWED (core wins, R6). Fail-open: if the lazy import or the merge
    raises, the core list is returned unchanged.

    Import topology (2212-7): ``plugin_fragments`` is imported LAZILY here with the
    dual path, NOT at module level — a module-level ``from lib import …`` would break
    the ``__main__`` drift self-check (``python3 lib/hook_registry.py``, where
    ``sys.path[0] == lib/``), exactly as the other lib modules avoid lib imports.
    """
    core = EVENT_REGISTRY.get(event, [])
    try:
        try:
            from lib import plugin_fragments
        except ImportError:
            import plugin_fragments  # type: ignore  # noqa: F401  (dual-path: lib/ on sys.path[0])
        return plugin_fragments.merged_event_entries(event, core)
    except Exception as exc:
        _report_loader_unavailable("hook_registry.get_entries", exc)
        return core  # fail-open: core-only on any loader error


# rp1-home#2613 (RP-F6): the loader fallbacks used to return core with no log, so an
# import-time bug in plugin_fragments.py silently dropped every plugin entry and
# detector. One report per process is enough: every fallback site fails on the same
# root cause, and each hook dispatch is its own process.
_LOADER_UNAVAILABLE_REPORTED: list[str] = []


def _reset_loader_unavailable_report() -> None:
    """Forget that the loader failure was reported (tests)."""
    _LOADER_UNAVAILABLE_REPORTED.clear()


def _report_loader_unavailable(where: str, exc: BaseException) -> None:
    """Report, once per process, that a plugin-fragment loader fallback fired: one
    stderr line plus a block-queue row (``reason_class="plugin_fragment_loader"``, the
    class ``plugin_fragments._log`` uses, K-LOADER). Fail-soft: never raises, and the
    caller still returns core."""
    if _LOADER_UNAVAILABLE_REPORTED:
        return
    _LOADER_UNAVAILABLE_REPORTED.append(where)
    # The dual-path fallback import usually fails with "No module named
    # 'plugin_fragments'" while handling the REAL error from the first path, so name
    # that one too — it is what the operator has to fix.
    cause = exc.__cause__ or exc.__context__
    detail = f"{exc!r}" + (f", raised while handling {cause!r}" if cause is not None else "")
    message = (
        f"plugin-fragment loader unavailable in {where} ({detail}); every plugin hook "
        "entry and plugin detector is skipped — core only."
    )
    try:
        import sys

        print(message, file=sys.stderr)
    except Exception:
        pass
    try:
        try:
            from lib.block_logger import log_hook_block
        except ImportError:
            from block_logger import log_hook_block  # type: ignore  # (dual path)
        log_hook_block(hook="plugin_fragments", reason=message,
                       reason_class="plugin_fragment_loader")
    except Exception:
        pass


def get_hook_path(name: str) -> str:
    """Resolve a hook basename to its on-disk path (extension-aware).

    Mirrors ``detector_registry.get_detector_path`` but handles both ``.py`` and
    ``.sh`` — ``check-approval-sentinel`` is a shell hook. Returns the ``.py`` path
    as the default when neither extension exists on disk (matching
    ``get_detector_path``'s not-found behavior), so a caller always receives a
    deterministic path to report in an error.

    rp1-home#2212 (KD-1): a merged fragment entry carries a RESOLVED ABSOLUTE path in
    ``Entry.module`` (built by ``merged_event_entries``); return such a path unchanged
    when it already resolves to an existing file, so ``_run_inprocess`` /
    ``_run_subprocess`` import from the plugin root. This preserves core behavior
    exactly — core entries are bare basenames, which never take this branch.
    """
    if os.path.isabs(name) and os.path.exists(name):
        return name
    for ext in (".py", ".sh"):
        candidate = os.path.join(HOOKS_DIR, name + ext)
        if os.path.exists(candidate):
            return candidate
    return os.path.join(HOOKS_DIR, name + ".py")


# ─────────────────────────────────────────────────────────────────────────────
# Drift validation (settings.json is authoritative)
# ─────────────────────────────────────────────────────────────────────────────
def _command_to_basename(command: str) -> str:
    """Extract a hook basename (no extension) from a settings.json command string.

    Handles ``python3 $HOME/.claude/hooks/foo.py`` and
    ``$HOME/.claude/hooks/bar.sh`` alike — the script path is the last
    whitespace-separated token.
    """
    parts = command.strip().split()
    if not parts:
        return ""
    base = os.path.basename(parts[-1])
    for ext in (".py", ".sh"):
        if base.endswith(ext):
            return base[: -len(ext)]
    return base


def _is_dispatcher_command(command: str) -> bool:
    """True iff ``command`` invokes ``hook-dispatcher.py``.

    The dispatcher's own registration — the #1731 capture-only shadow line
    (``hook-dispatcher.py --shadow <event>``) and, post-#1732, the live cutover
    line — is a META-registration that OBSERVES the corpus; it is NOT a member of
    it. The drift check MUST ignore it, else the naive last-token
    :func:`_command_to_basename` would read the trailing ``<event>`` arg as a bogus
    module name and report false drift (settings.json is authoritative for the
    corpus, and the dispatcher is not part of the corpus it dispatches).
    """
    for token in command.strip().split():
        base = os.path.basename(token)
        if base in ("hook-dispatcher.py", "hook-dispatcher"):
            return True
    return False


def _parse_settings_entries(settings_path: str) -> dict[str, list[tuple[str, str]]]:
    """Parse settings.json into ``{event: [(matcher, module_basename), ...]}`` in
    array order — the exact seed the static ``EVENT_REGISTRY`` was generated from.
    """
    with open(settings_path) as fh:
        settings = json.load(fh)
    result: dict[str, list[tuple[str, str]]] = {}
    for event in ("PreToolUse", "PostToolUse"):
        seq: list[tuple[str, str]] = []
        for group in settings.get("hooks", {}).get(event, []):
            matcher = group.get("matcher", "") or ""
            for hook in group.get("hooks", []):
                command = hook.get("command", "")
                if _is_dispatcher_command(command):
                    continue  # meta-registration (#1731 shadow / #1732 cutover) — not a corpus hook
                module = _command_to_basename(command)
                if module:
                    seq.append((matcher, module))
        result[event] = seq
    return result


def _has_live_dispatcher_registration(settings_path: str) -> bool:
    """True iff BOTH PreToolUse and PostToolUse carry a non-shadow dispatcher line.

    Distinguishes the sanctioned #1732 cutover shape (corpus migrated to the
    registry, dispatcher meta-registrations present) from an accidental wholesale
    hooks-wipe (corpus empty AND no dispatcher line), which must still report drift.
    """
    try:
        with open(settings_path) as fh:
            settings = json.load(fh)
    except (OSError, json.JSONDecodeError):
        return False
    for event in ("PreToolUse", "PostToolUse"):
        found = False
        for group in settings.get("hooks", {}).get(event, []):
            for hook in group.get("hooks", []):
                command = hook.get("command", "")
                if _is_dispatcher_command(command) and "--shadow" not in command:
                    found = True
        if not found:
            return False
    return True


def validate_against_settings(settings_path: str | None = None) -> dict:
    """Diff the static ``EVENT_REGISTRY`` against a fresh settings.json parse.

    Returns ``{"matches": bool, "drift": [...], "mode": "corpus"|"dispatcher"}``.
    Pre-cutover (``mode: "corpus"``) settings.json is authoritative: a non-empty
    ``drift`` means the committed literal must be regenerated (a registration was
    added, removed, or reordered). The diff is ORDER-SENSITIVE because
    settings.json array order is load-bearing. This is the callable form of
    the #1730 V1 verify ("registry (event,matcher,module) tuples vs a fresh jq
    extraction from settings.json is empty").

    Post-#1732-cutover (``mode: "dispatcher"``): settings.json carries ONLY the
    two dispatcher meta-registrations, the corpus parse is empty, and the registry
    is the sole corpus surface — nothing to diff (full single-surface enforcement
    is #1735). The dispatcher-mode branch requires a live (non-shadow) dispatcher
    line for BOTH events, so a wholesale hooks-wipe still reports drift.
    """
    path = settings_path or DEFAULT_SETTINGS_PATH
    parsed = _parse_settings_entries(path)
    if (
        not parsed.get("PreToolUse")
        and not parsed.get("PostToolUse")
        and _has_live_dispatcher_registration(path)
    ):
        return {"matches": True, "drift": [], "mode": "dispatcher"}
    drift: list[dict] = []
    for event in ("PreToolUse", "PostToolUse"):
        registry_tuples = [(e.matcher, e.module) for e in EVENT_REGISTRY.get(event, [])]
        settings_tuples = parsed.get(event, [])
        if registry_tuples != settings_tuples:
            drift.append(
                {
                    "event": event,
                    "in_registry_not_settings": [t for t in registry_tuples if t not in settings_tuples],
                    "in_settings_not_registry": [t for t in settings_tuples if t not in registry_tuples],
                    "order_mismatch": (
                        sorted(registry_tuples) == sorted(settings_tuples)
                        and registry_tuples != settings_tuples
                    ),
                }
            )
    return {"matches": len(drift) == 0, "drift": drift, "mode": "corpus"}


if __name__ == "__main__":
    # Standalone drift self-check: exit 0 = registry matches settings.json, 1 = drift.
    import sys

    report = validate_against_settings()
    total = sum(len(v) for v in EVENT_REGISTRY.values())
    if report["matches"]:
        print(f"hook_registry: OK — {total} entries match settings.json array order.")
        sys.exit(0)
    print(f"hook_registry: DRIFT — registry ({total} entries) diverges from settings.json:")
    print(json.dumps(report["drift"], indent=2))
    sys.exit(1)

"""Shared delegation for the core tier's priority-detector routing stubs (ruling D21).

GENERATED by the core-tier export (rp1-home toolkit-export/gen-core-registries.py) — do
not edit by hand.

The kept-core priority detectors keep their name and their PRIORITY_GROUP slot in the
core tier (the dispatcher's first-match order is load-bearing) but carry no routing logic
of their own. Each stub calls :func:`delegate`, which:

* finds the stub's premium plugin among the enabled, fragment-bearing plugins
  (``lib.plugin_fragments.discover_plugins``) — not there: no match (``None``);
* the plugin ships ``hooks/priority-detectors/<detector>.py``: loads it and returns its
  ``run_detection(prompt, input_data)`` — the same contract as a core detector;
* the plugin is there without that module: no match, plus one stderr line.

A delegated module runs contained: its prints go to stderr (stdout is the prompt
dispatcher's JSON channel), any exception — SystemExit included — is reported and treated
as no match, and a result that is not a well-formed detector result is dropped.
"""

import contextlib
import importlib.util
import os
import sys

_ROOTS = None  # plugin name -> root, discovered once per process
_MODULES = {}


def _plugin_roots():
    global _ROOTS
    if _ROOTS is None:
        try:
            try:
                from lib import plugin_fragments
            except ImportError:
                import plugin_fragments  # type: ignore  # dual path: lib/ on sys.path[0]
            _ROOTS = {p.name: p.root for p in plugin_fragments.discover_plugins()}
        except Exception as exc:
            print(f"priority-detector stubs: plugin discovery failed ({exc!r}); no match", file=sys.stderr)
            _ROOTS = {}
    return _ROOTS


def _result_problem(result):
    if not result:
        return None
    if not isinstance(result, dict):
        return f"result is {type(result).__name__}, expected a dict"
    hso = result.get("hookSpecificOutput")
    if isinstance(hso, dict):
        ctx = hso.get("additionalContext")
        if ctx and not isinstance(ctx, str):
            return "hookSpecificOutput.additionalContext is not a str"
    ctx = result.get("additionalContext")
    if ctx and not isinstance(ctx, str):
        return "additionalContext is not a str"
    return None


def delegate(detector, plugin, prompt, input_data):
    """Run ``detector``'s routing logic from ``plugin``, or return None (no match)."""
    root = _plugin_roots().get(plugin)
    if root is None:
        return None
    path = os.path.join(root, "hooks", "priority-detectors", detector + ".py")
    if not os.path.isfile(path):
        print(f"{detector}: plugin {plugin} is enabled but ships no hooks/priority-detectors/{detector}.py; no match",
              file=sys.stderr)
        return None
    try:
        with contextlib.redirect_stdout(sys.stderr):
            module = _MODULES.get(path)
            if module is None:
                spec = importlib.util.spec_from_file_location(
                    "priority_detector_" + detector.replace("-", "_"), path)
                if spec is None or spec.loader is None:
                    raise ImportError(f"cannot load {path}")
                module = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(module)
                _MODULES[path] = module
            run = getattr(module, "run_detection", None)
            if run is None:
                print(f"{detector}: {path} defines no run_detection(); no match", file=sys.stderr)
                return None
            result = run(prompt, input_data)
    except KeyboardInterrupt:
        raise
    except BaseException as exc:
        print(f"{detector}: delegated detector failed ({exc!r}); no match", file=sys.stderr)
        return None
    problem = _result_problem(result)
    if problem:
        print(f"{detector}: delegated detector returned a malformed result ({problem}); no match", file=sys.stderr)
        return None
    return result or None
